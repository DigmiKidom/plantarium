#!/usr/bin/env node
// Builds supabase/setup.sql = all migrations + the species seed, for a one-time paste
// into the Supabase SQL Editor on a NEW, empty project.
// Usage: npm run db:setup-sql
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
execFileSync(process.execPath, [join(root, "scripts/build-seed-sql.mjs"), "--publish"], { stdio: "inherit" });

const migDir = join(root, "supabase/migrations");
const parts = readdirSync(migDir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => `-- ===== ${f} =====\n${readFileSync(join(migDir, f), "utf8")}`);

const header = `-- Plantarium – full database setup (schema + security + search + ${"species"} data)
-- Run ONCE on a new Supabase project: SQL Editor → New query → paste → Run.
-- Generated by scripts/build-setup-sql.mjs – do not edit by hand.
`;
writeFileSync(
  join(root, "supabase/setup.sql"),
  [header, ...parts, "-- ===== seed.sql =====", readFileSync(join(root, "supabase/seed.sql"), "utf8")].join("\n\n"),
);
console.log("Wrote supabase/setup.sql");
