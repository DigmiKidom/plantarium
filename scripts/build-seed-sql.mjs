#!/usr/bin/env node
// Generates supabase/seed.sql from src/data/species.json.
// Usage: node scripts/build-seed-sql.mjs [--publish]
// `supabase db reset` runs seed.sql automatically; you can also paste it into the Supabase SQL editor.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { species } = JSON.parse(readFileSync(join(root, "src/data/species.json"), "utf8"));
const publish = process.argv.includes("--publish");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a, type = "text") => `array[${a.map(q).join(",")}]::${type}[]`;
const bool = (v) => (v === null || v === undefined ? "null" : v ? "true" : "false");

const lines = [
  "-- Generated by scripts/build-seed-sql.mjs – do not edit by hand.",
  "begin;",
];

for (const s of species) {
  const c = s.care;
  lines.push(`
with sp as (
  insert into public.species (slug, scientific_name, common_name_he, other_names_he, common_name_en, family, category, difficulty,
    summary_he, native_region_he, growth_rate, max_height_cm, is_toxic_pets, tags, published_at)
  values (${q(s.slug)}, ${q(s.scientific_name)}, ${q(s.common_name_he)}, ${arr(s.other_names_he)}, ${q(s.common_name_en)},
    ${q(s.family)}, ${q(s.category)}, ${q(s.difficulty)}, ${q(s.summary_he)}, ${q(s.native_region_he)}, ${q(s.growth_rate)},
    ${s.max_height_cm ?? "null"}, ${bool(s.is_toxic_pets)}, ${arr(s.tags)}, ${publish ? "now()" : "null"})
  on conflict (slug) do update set
    scientific_name = excluded.scientific_name, common_name_he = excluded.common_name_he,
    other_names_he = excluded.other_names_he, common_name_en = excluded.common_name_en, family = excluded.family,
    category = excluded.category, difficulty = excluded.difficulty, summary_he = excluded.summary_he,
    native_region_he = excluded.native_region_he, growth_rate = excluded.growth_rate,
    max_height_cm = excluded.max_height_cm, is_toxic_pets = excluded.is_toxic_pets, tags = excluded.tags
  returning id
)
insert into public.species_care (species_id, light, light_notes_he, water_interval_min_days, water_interval_max_days,
  water_notes_he, humidity_min, humidity_max, temp_min_c, temp_max_c, fertilize_interval_days, fertilize_season,
  medium, medium_notes_he, seasonal)
select id, ${q(c.light)}, ${q(c.light_notes_he)}, ${c.water_interval_min_days}, ${c.water_interval_max_days},
  ${q(c.water_notes_he)}, ${c.humidity_min}, ${c.humidity_max}, ${c.temp_min_c}, ${c.temp_max_c},
  ${c.fertilize_interval_days}, ${q(c.fertilize_season)}, ${arr(c.medium, "medium_type")}, ${q(c.medium_notes_he)},
  ${q(JSON.stringify(c.seasonal))}::jsonb
from sp
on conflict (species_id) do update set
  light = excluded.light, light_notes_he = excluded.light_notes_he,
  water_interval_min_days = excluded.water_interval_min_days, water_interval_max_days = excluded.water_interval_max_days,
  water_notes_he = excluded.water_notes_he, humidity_min = excluded.humidity_min, humidity_max = excluded.humidity_max,
  temp_min_c = excluded.temp_min_c, temp_max_c = excluded.temp_max_c,
  fertilize_interval_days = excluded.fertilize_interval_days, fertilize_season = excluded.fertilize_season,
  medium = excluded.medium, medium_notes_he = excluded.medium_notes_he, seasonal = excluded.seasonal;`);
}

lines.push("commit;", "");
const out = join(root, "supabase/seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${species.length} species to supabase/seed.sql${publish ? " (published)" : " (unpublished drafts)"}`);
