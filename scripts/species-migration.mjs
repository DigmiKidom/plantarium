#!/usr/bin/env node
// Plant species: src/data/species.json is the editing source, migrations are what reaches the database.
// This writes a NEW migration with every species from the JSON that no migration adds yet (insert-only:
// it never overwrites edits made on the site). Then: npm run db:test → npm run db:push.
// Usage: npm run db:species        (or --check: exit 1 if the JSON has species no migration adds – used in CI)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const migDir = join(root, "supabase/migrations");
const { species } = JSON.parse(readFileSync(join(root, "src/data/species.json"), "utf8"));

const inMigrations = new Set();
for (const f of readdirSync(migDir).filter((f) => f.endsWith(".sql"))) {
  for (const m of readFileSync(join(migDir, f), "utf8").matchAll(/insert into public\.species \([^)]*\)\s*values \('([a-z0-9-]+)'/g)) {
    inMigrations.add(m[1]);
  }
}
const missing = species.filter((s) => !inMigrations.has(s.slug));

if (process.argv.includes("--check")) {
  if (missing.length) {
    console.log(`❌ ${missing.length} species in species.json aren't in any migration: ${missing.slice(0, 10).map((s) => s.slug).join(", ")}…`);
    console.log("   Run: npm run db:species");
    process.exit(1);
  }
  console.log(`✅ all ${species.length} species in species.json are in migrations`);
  process.exit(0);
}
if (!missing.length) {
  console.log("Nothing to do – every species in species.json is already in a migration.");
  process.exit(0);
}

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a, type = "text") => `array[${(a ?? []).map(q).join(",")}]::${type}[]`;
const bool = (v) => (v === null || v === undefined ? "null" : v ? "true" : "false");
const num = (v) => (v === null || v === undefined ? "null" : String(v));

const blocks = missing.map((s) => {
  const c = s.care;
  return `with sp as (
  insert into public.species (slug, scientific_name, common_name_he, other_names_he, common_name_en, family, category, difficulty,
    summary_he, native_region_he, growth_rate, max_height_cm, is_toxic_pets, tags, published_at)
  values (${q(s.slug)}, ${q(s.scientific_name)}, ${q(s.common_name_he)}, ${arr(s.other_names_he)}, ${q(s.common_name_en)},
    ${q(s.family)}, ${q(s.category)}, ${q(s.difficulty)}, ${q(s.summary_he)}, ${q(s.native_region_he)}, ${q(s.growth_rate)},
    ${num(s.max_height_cm)}, ${bool(s.is_toxic_pets)}, ${arr(s.tags)}, now())
  on conflict do nothing
  returning id
)
insert into public.species_care (species_id, light, light_notes_he, water_interval_min_days, water_interval_max_days,
  water_notes_he, humidity_min, humidity_max, temp_min_c, temp_max_c, fertilize_interval_days, fertilize_season,
  medium, medium_notes_he, pruning_he, propagation_he, seasonal)
select id, ${q(c.light)}, ${q(c.light_notes_he)}, ${c.water_interval_min_days}, ${c.water_interval_max_days},
  ${q(c.water_notes_he)}, ${num(c.humidity_min)}, ${num(c.humidity_max)}, ${num(c.temp_min_c)}, ${num(c.temp_max_c)},
  ${num(c.fertilize_interval_days)}, ${q(c.fertilize_season)}, ${arr(c.medium, "medium_type")}, ${q(c.medium_notes_he)},
  ${q(c.pruning_he)}, ${q(c.propagation_he)}, ${q(JSON.stringify(c.seasonal))}::jsonb
from sp;
`;
});

const stamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
const file = join(migDir, `${stamp}_species_${missing.length}.sql`);
writeFileSync(file, [`-- Plantarium – ${missing.length} plant species from species.json (generated by scripts/species-migration.mjs).`, "", ...blocks].join("\n"));
console.log(`Wrote ${file}`);
